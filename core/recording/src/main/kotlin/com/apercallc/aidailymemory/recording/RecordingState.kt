package com.apercallc.aidailymemory.recording

enum class RecordingStatus {
    IDLE,
    STARTING,
    RECORDING,
    PAUSED,

    /** Resume requested; the microphone is reopening. Not capturing until `Started`. */
    RESUMING,
    INTERRUPTED,
    RECOVERING,
    STOPPING,
    COMPLETED,
}

/** Why capture could not start or stopped producing audio. Shown to the user; never swallowed. */
enum class CaptureProblem {
    PERMISSION_DENIED,
    MICROPHONE_UNAVAILABLE,
    PHONE_CALL,
    FOREGROUND_START_NOT_ALLOWED,
    STORAGE_LOW,

    /** Local audio encryption keys are unusable; recording unencrypted is never an option. */
    ENCRYPTION_UNAVAILABLE,

    /**
     * The recording notification cannot be shown (notifications or its channel turned off).
     * The microphone is never open without a visible indicator (AGENTS.md rule 1).
     */
    INDICATOR_HIDDEN,
    PROCESS_RESTARTED,
    DEVICE_REBOOTED,
    UNKNOWN,
}

/**
 * Stable, device-generated session identifier (see ADR-0006). Generated by the caller so
 * the reducer stays deterministic.
 */
@JvmInline
value class SessionId(val value: String) {
    init {
        require(value.isNotBlank()) { "SessionId must not be blank" }
    }
}

/**
 * Snapshot of the recording domain.
 *
 * [revision] increases by exactly one on every applied transition. It orders persisted
 * transitions and lets the watch discard stale state snapshots (ADR-0008). It must be
 * restored from the persisted journal after process death, never restarted from zero.
 *
 * [pausedBySchedule] is true only for a pause the daily rhythm made (quiet time, ADR-0012).
 * Only such a pause is ever resumed automatically; a pause the user made never is.
 */
data class RecordingState(
    val status: RecordingStatus,
    val sessionId: SessionId?,
    val revision: Long,
    val problem: CaptureProblem?,
    val pausedBySchedule: Boolean = false,
) {
    init {
        require(!pausedBySchedule || status == RecordingStatus.PAUSED) {
            "only a PAUSED state can be paused by the schedule"
        }
        // Every non-idle state belongs to a session; this also rejects corrupt persisted state.
        require((status == RecordingStatus.IDLE) == (sessionId == null)) {
            "sessionId must be null exactly when status is IDLE (status=$status)"
        }
        require(revision >= 0) { "revision must not be negative" }
    }

    companion object {
        val Initial = RecordingState(
            status = RecordingStatus.IDLE,
            sessionId = null,
            revision = 0,
            problem = null,
        )
    }
}

sealed interface RecordingEvent

/**
 * User intent. May originate from the phone UI, the notification, or the watch, and may be
 * delivered more than once. A duplicate command whose intent is already satisfied is
 * [Transition.Ignored], not an error.
 */
sealed interface RecordingCommand : RecordingEvent {
    data class Start(val sessionId: SessionId) : RecordingCommand
    data object Pause : RecordingCommand
    data object Resume : RecordingCommand
    data object Stop : RecordingCommand
    data object Reset : RecordingCommand

    /**
     * From the daily rhythm (ADR-0012), never from a person. Schedule commands are never
     * rejected: when they don't apply (nothing is recording, the user already paused) they
     * are ignored, so a schedule tick can't produce an error the user didn't cause.
     */
    data object ScheduledPause : RecordingCommand

    /** Resumes only a pause the schedule made. */
    data object ScheduledResume : RecordingCommand

    /** Bedtime: ends the session like Stop. */
    data object ScheduledStop : RecordingCommand
}

/**
 * Fact reported by the capture engine. Never sent by the watch. Each signal names the
 * session it belongs to, so a late callback from a previous session is rejected instead of
 * being applied to the current one.
 */
sealed interface CaptureSignal : RecordingEvent {
    val sessionId: SessionId

    /** Audio is flowing: the first buffer arrived after a start or a resume. */
    data class Started(override val sessionId: SessionId) : CaptureSignal
    data class StartFailed(
        override val sessionId: SessionId,
        val problem: CaptureProblem,
    ) : CaptureSignal
    data class Interrupted(
        override val sessionId: SessionId,
        val problem: CaptureProblem,
    ) : CaptureSignal
    data class RecoveryStarted(override val sessionId: SessionId) : CaptureSignal
    data class Recovered(override val sessionId: SessionId) : CaptureSignal
    data class Stopped(override val sessionId: SessionId) : CaptureSignal
}

sealed interface Transition {
    val state: RecordingState
    val event: RecordingEvent

    /** State changed. Persist [state] before performing side effects that depend on it. */
    data class Applied(
        val previous: RecordingState,
        override val state: RecordingState,
        override val event: RecordingEvent,
    ) : Transition

    /** Duplicate command whose intent already holds. Acknowledge with the current state. */
    data class Ignored(
        override val state: RecordingState,
        override val event: RecordingEvent,
    ) : Transition

    /** Event not valid in the current state. State is unchanged; the caller must surface it. */
    data class Rejected(
        override val state: RecordingState,
        override val event: RecordingEvent,
    ) : Transition
}

/** Pure, deterministic reducer. No Android types, clocks, IDs, or I/O. */
object RecordingStateMachine {
    fun reduce(current: RecordingState, event: RecordingEvent): Transition {
        val status = current.status
        if (event is CaptureSignal && event.sessionId != current.sessionId) {
            return Transition.Rejected(current, event)
        }
        val next: RecordingState? = when (event) {
            is RecordingCommand.Start -> when (status) {
                RecordingStatus.IDLE, RecordingStatus.COMPLETED ->
                    RecordingState(RecordingStatus.STARTING, event.sessionId, current.revision, null)
                else -> null
            }

            RecordingCommand.Pause -> when (status) {
                // Pausing wins over automatic recovery: a privacy pause must never be undone
                // by the capture engine.
                RecordingStatus.RECORDING,
                RecordingStatus.RESUMING,
                RecordingStatus.INTERRUPTED,
                RecordingStatus.RECOVERING,
                -> current.moveTo(RecordingStatus.PAUSED)
                // Pausing during quiet time makes it the user's pause: when quiet time ends,
                // it stays paused.
                RecordingStatus.PAUSED ->
                    current.moveToIf(current.pausedBySchedule, RecordingStatus.PAUSED)
                else -> null
            }

            RecordingCommand.ScheduledPause -> when (status) {
                RecordingStatus.RECORDING,
                RecordingStatus.RESUMING,
                RecordingStatus.INTERRUPTED,
                RecordingStatus.RECOVERING,
                -> current.moveTo(RecordingStatus.PAUSED).copy(pausedBySchedule = true)
                else -> null
            }

            RecordingCommand.ScheduledResume -> current.moveToIf(
                status == RecordingStatus.PAUSED && current.pausedBySchedule,
                RecordingStatus.RESUMING,
            )

            // Never straight to RECORDING: after a restart the service may be gone, so the
            // engine must confirm audio is flowing (`Started`) before we claim capture.
            // From INTERRUPTED this is the user's "try again" (e.g. "tap to resume" after a
            // reboot, which the engine may never recover from by itself).
            RecordingCommand.Resume -> when (status) {
                RecordingStatus.PAUSED, RecordingStatus.INTERRUPTED ->
                    current.moveTo(RecordingStatus.RESUMING)
                else -> null
            }

            RecordingCommand.Stop, RecordingCommand.ScheduledStop -> when (status) {
                RecordingStatus.STARTING,
                RecordingStatus.RECORDING,
                RecordingStatus.PAUSED,
                RecordingStatus.RESUMING,
                RecordingStatus.INTERRUPTED,
                RecordingStatus.RECOVERING,
                -> current.moveTo(RecordingStatus.STOPPING, current.problem)
                else -> null
            }

            RecordingCommand.Reset -> when (status) {
                RecordingStatus.COMPLETED -> RecordingState.Initial.copy(revision = current.revision)
                else -> null
            }

            is CaptureSignal.Started -> current.moveToIf(
                status == RecordingStatus.STARTING || status == RecordingStatus.RESUMING,
                RecordingStatus.RECORDING,
            )

            is CaptureSignal.StartFailed -> when (status) {
                RecordingStatus.STARTING ->
                    RecordingState(RecordingStatus.IDLE, null, current.revision, event.problem)
                else -> null
            }

            // A failed resume keeps the session (unlike a failed start) and becomes visible.
            is CaptureSignal.Interrupted -> when (status) {
                RecordingStatus.RECORDING, RecordingStatus.RESUMING, RecordingStatus.RECOVERING ->
                    current.moveTo(RecordingStatus.INTERRUPTED, event.problem)
                else -> null
            }

            is CaptureSignal.RecoveryStarted -> when (status) {
                RecordingStatus.INTERRUPTED ->
                    current.moveTo(RecordingStatus.RECOVERING, current.problem)
                else -> null
            }

            is CaptureSignal.Recovered ->
                current.moveToIf(status == RecordingStatus.RECOVERING, RecordingStatus.RECORDING)

            // A session that ended after an interruption keeps the cause for the summary.
            is CaptureSignal.Stopped -> when (status) {
                RecordingStatus.STOPPING ->
                    current.moveTo(RecordingStatus.COMPLETED, current.problem)
                else -> null
            }
        }

        return when {
            next != null -> Transition.Applied(
                previous = current,
                state = next.copy(revision = current.revision + 1),
                event = event,
            )
            isAlreadySatisfied(current, event) -> Transition.Ignored(current, event)
            else -> Transition.Rejected(current, event)
        }
    }

    private fun isAlreadySatisfied(current: RecordingState, event: RecordingEvent): Boolean {
        val status = current.status
        return when (event) {
            // Only a retry of the same start is a duplicate; a different session is a conflict.
            is RecordingCommand.Start ->
                event.sessionId == current.sessionId &&
                    (status == RecordingStatus.STARTING || status == RecordingStatus.RECORDING)
            RecordingCommand.Pause -> status == RecordingStatus.PAUSED
            // Schedule commands never produce a rejection (see ScheduledPause).
            RecordingCommand.ScheduledPause,
            RecordingCommand.ScheduledResume,
            RecordingCommand.ScheduledStop,
            -> true
            // While the engine is already recovering, a user resume adds nothing.
            RecordingCommand.Resume ->
                status == RecordingStatus.RESUMING ||
                    status == RecordingStatus.RECORDING ||
                    status == RecordingStatus.RECOVERING
            RecordingCommand.Stop ->
                status == RecordingStatus.STOPPING || status == RecordingStatus.COMPLETED
            RecordingCommand.Reset -> status == RecordingStatus.IDLE
            is CaptureSignal -> false
        }
    }

    private fun RecordingState.moveTo(
        status: RecordingStatus,
        problem: CaptureProblem? = null,
    ): RecordingState = copy(status = status, problem = problem, pausedBySchedule = false)

    private fun RecordingState.moveToIf(
        condition: Boolean,
        status: RecordingStatus,
    ): RecordingState? = if (condition) moveTo(status) else null
}
